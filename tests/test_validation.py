def test_label_mpge_matches_hand_calculation():
    # 0.7 * 3370.5 / 16.89 = 139.69
    assert va.label_mpge(16.89) == pytest.approx(139.69, abs=0.01)


def test_combined_consumption_weights():
    assert va.combined_consumption(10.0, 10.0) == pytest.approx(10.0)
    assert va.combined_consumption(20.0, 30.0) == pytest.approx(0.55 * 20 + 0.45 * 30)


def test_label_range_hand_calculation():
    # 0.7 * (60 / 1.0) / (20 / 100) = 210 miles
    assert va.label_range_miles(60.0, 20.0, 1.0) == pytest.approx(210.0)


def test_lower_charging_efficiency_gives_longer_range():
    assert va.label_range_miles(60.0, 20.0, 0.85) > va.label_range_miles(60.0, 20.0, 0.95)


@pytest.mark.parametrize("bad", [0.0, -0.5, 1.2])
def test_label_range_rejects_bad_efficiency(bad):
    with pytest.raises(ValueError):
        va.label_range_miles(60.0, 20.0, bad)



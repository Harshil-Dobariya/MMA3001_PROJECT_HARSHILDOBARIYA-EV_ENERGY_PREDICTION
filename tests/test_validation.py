"""Tests for ev_energy.validation."""

import json
import math

import numpy as np
import pandas as pd
import pytest

from ev_energy import physics_model as pm
from ev_energy import validation as va
from test_ml_models import FAST_PARAMS, make_vehicles


def small_cycles():
    """Short synthetic city and highway cycles (accelerate, cruise, brake)."""
    t = np.arange(0.0, 121.0)
    city = np.concatenate([np.linspace(0, 15, 21), np.full(80, 15.0), np.linspace(15, 0, 20)])
    hwy = np.concatenate([np.linspace(0, 27, 21), np.full(80, 27.0), np.linspace(27, 0, 20)])
    return {"city": pm.DriveCycle("city", t, city), "hwy": pm.DriveCycle("hwy", t, hwy)}


def vehicles_with_real_physics(n_models=30):
    """Synthetic vehicles whose physics features come from real integration."""
    df = make_vehicles(n_models=n_models)
    df = pm.add_physics_features(df, small_cycles())
    # Targets generated by the physics model itself, plus noise.
    rng = np.random.default_rng(1)
    for c in ("city", "hwy"):
        df[f"{c}_kwh_per_100mi"] = pm.consumption_kwh_per_100mi(
            df[f"{c}_e_pos_j"], df[f"{c}_e_neg_j"], df[f"{c}_duration_s"], df[f"{c}_dist_m"],
            0.8, 0.6, 300.0,
        ) + rng.normal(0, 0.2, len(df))
    return df



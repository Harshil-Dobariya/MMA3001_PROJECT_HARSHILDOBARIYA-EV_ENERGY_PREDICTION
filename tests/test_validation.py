def test_out_of_domain_flags_only_extreme_vehicles():
    df = make_vehicles()
    test = df.iloc[:3].copy()
    test.loc[test.index[0], "etw_kg"] = 10_000.0  # far heavier than any training car
    flags = va.out_of_domain(df, test)
    assert flags.tolist() == [True, False, False]


def test_perturb_scales_input_and_recomputes_physics():
    df = vehicles_with_real_physics()
    heavier = va.perturb(df, "etw_kg", 1.1, small_cycles())
    assert np.allclose(heavier["etw_kg"], 1.1 * df["etw_kg"])
    assert (heavier["city_e_pos_j"] > df["city_e_pos_j"]).all()


def test_physics_responds_in_the_physically_correct_direction():
    df = vehicles_with_real_physics()
    train, test = df.iloc[:60], df.iloc[60:]
    sens = va.sensitivity(train, test, FAST_PARAMS, small_cycles())
    physics = sens[sens["model"] == "physics"]
    assert (physics["median_elasticity"] > 0).all()
    assert (physics["fraction_negative"] == 0).all()

def test_fit_and_predict_gives_every_model_without_gaps():
    df = make_vehicles()
    train, test = df.iloc[:60], df.iloc[60:]
    preds = va.fit_and_predict(train, test, FAST_PARAMS)
    pred_cols = [c for c in preds.columns if "__" in c]
    assert len(pred_cols) == 20  # 10 models x 2 cycles
    assert preds[pred_cols].notna().all().all()


def test_fit_and_predict_physics_matches_physics_model():
    df = make_vehicles()
    train, test = df.iloc[:60], df.iloc[60:]
    preds = va.fit_and_predict(train, test, FAST_PARAMS)
    expected = pm.PhysicsModel().fit(train).predict(test, "city")
    assert np.allclose(preds["physics__city"], expected)


def test_metrics_table_rows():
    df = make_vehicles()
    preds = va.fit_and_predict(df.iloc[:60], df.iloc[60:], FAST_PARAMS)
    table = va.metrics_table(preds)
    assert len(table) == 20
    assert {"rmse", "mae", "r2", "max_abs_error"} <= set(table.columns)


def test_bootstrap_of_identical_models_shows_no_difference():
    df = make_vehicles()
    preds = df.copy()
    preds["physics__city"] = df["city_kwh_per_100mi"] + 1.0
    preds["copy__city"] = preds["physics__city"]
    boot = va.group_bootstrap(preds, ["copy"], "city", n_boot=200)
    row = boot.iloc[0]
    assert row["rmse"] == pytest.approx(1.0)
    assert row["diff_vs_physics"] == pytest.approx(0.0)
    assert row["p_better_than_physics"] == 0.0


def test_bootstrap_detects_a_clearly_better_model():
    df = make_vehicles()
    preds = df.copy()
    preds["physics__city"] = df["city_kwh_per_100mi"] + 2.0
    preds["good__city"] = df["city_kwh_per_100mi"] + 0.1
    row = va.group_bootstrap(preds, ["good"], "city", n_boot=200).iloc[0]
    assert row["diff_hi"] < 0
    assert row["p_better_than_physics"] == 1.0
    assert row["rmse_lo"] <= row["rmse"] <= row["rmse_hi"]


